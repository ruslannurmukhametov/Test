# Источник: accounting.sales (MCP Dodo Sky), 10 заказов. Цены в ₽.
# (цена без скидки, цена со скидкой, тип скидки)
orders = [
 (1747,1385,"комбо «3 пиццы»"),
 (2128,1828,"комбо закусок"),
 (2015,2015,None),
 (2147,1549,"промо: листовка «Аррива за 1 ₽ от 1195 ₽»"),
 (1747,1385,"комбо «3 пиццы»"),
 (867,768,"комбо «2 закуски»"),
 (1352,1352,None),
 (1693,1693,None),
 (1206,989,"комбо «3 любые пиццы»"),
 (1641,1412,"комбо «2 пиццы»"),
]
P=sum(o[0] for o in orders); D=sum(o[1] for o in orders); n=len(orders)
print(f"Заказов: {n}, со скидкой: {sum(o[0]>o[1] for o in orders)}")
print(f"Чек без скидки {P/n:.0f} ₽, со скидкой {D/n:.0f} ₽, скидка {(P-D)/n:.0f} ₽ на заказ = {(P-D)/P:.1%}")
combo=sum(o[0]-o[1] for o in orders if o[2] and o[2].startswith("комбо")); promo=sum(o[0]-o[1] for o in orders if o[2] and o[2].startswith("промо"))
print(f"Из скидки: комбо {combo} ₽ ({combo/(P-D):.0%}), промо {promo} ₽ ({promo/(P-D):.0%})")
