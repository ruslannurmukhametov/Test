# Разложение разницы среднего чека Тюмень-1 vs Надым-1 (июль+август 2026)
# на эффект структуры (доля доставки) и эффект чека внутри канала.
# Суммы из finances.sales.units.monthly (MCP Dodo Sky), без НДС.
T = {"Delivery": (13005666+889999+668839+81237+90947+11932+40730+14597+1238 + 879736+12096205+720588+126075+80871+10057+47928+14352,
                  7793+495+472+44+49+3+24+6+1 + 466+7344+455+63+40+6+27+9),
     "Dine-in": (1484815+2077216+154775+451729+20118+33417+20739+3062+0+299 + 1527746+1175030+352933+22477+106678+14496+20525+0+3935+2247,
                 1995+3230+402+963+16+32+16+3+3+1 + 2558+1637+819+22+266+17+16+5+4+2)}
N = {"Delivery": (11848622+38495+348361+0 + 12008986+335380+46929+0, 8010+26+221+3 + 8085+221+33+3),
     "Dine-in": (2453620+178415+2260253+41979+1638+15395+6802+3577 + 2158954+2538075+21698+224888+15105+15764+777+3233+1417,
                 3829+362+2998+131+1+9+5+3 + 2932+4066+54+441+13+7+1+6+1)}
def stats(u):
    S=sum(v[0] for v in u.values()); O=sum(v[1] for v in u.values())
    return S/O, {c:(v[1]/O, v[0]/v[1]) for c,v in u.items()}
aT,cT=stats(T); aN,cN=stats(N)
print(f"Средний чек: Т {aT:.0f}, Н {aN:.0f}, разница {aT-aN:.0f}")
# симметричное разложение (средние веса)
mix = sum((cT[c][0]-cN[c][0])*(cT[c][1]+cN[c][1])/2 for c in cT)
rate = sum((cT[c][1]-cN[c][1])*(cT[c][0]+cN[c][0])/2 for c in cT)
for c in cT: print(c, f"доля Т {cT[c][0]:.1%} / Н {cN[c][0]:.1%}; чек Т {cT[c][1]:.0f} / Н {cN[c][1]:.0f}; вклад чека {(cT[c][1]-cN[c][1])*(cT[c][0]+cN[c][0])/2:+.0f}")
print(f"Эффект структуры (больше доставки): {mix:+.0f} ₽; эффект чека внутри каналов: {rate:+.0f} ₽; сумма {mix+rate:+.0f}")
