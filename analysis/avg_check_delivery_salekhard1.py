# Средний чек на доставку, Салехард-1, июль–август 2026
# Источник: finances.sales.units.monthly (MCP Dodo Sky), без НДС, ₽
jul = [(12255168,7904),(0,15),(370494,221),(103206,85)]
aug = [(15340935,9801),(532975,318),(112359,86),(0,35),(0,2)]
for name, rows in (("Июль", jul), ("Август", aug), ("Июль–август", jul+aug)):
    s=sum(r[0] for r in rows); o=sum(r[1] for r in rows)
    print(f"{name}: {s/o:.0f} ₽ ({o} заказов, {s} ₽)")
# Без заказов с нулевой суммой (наличные через приложение/сайт)
